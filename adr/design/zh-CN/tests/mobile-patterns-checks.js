'use strict';
// 通过可见DOM操作合成原型。测试不调用核心、不接触真实凭据。
window.runKeexMobilePatternChecks = function runKeexMobilePatternChecks() {
  const checks=[];
  const check=(name,value)=>{checks.push({name,passed:Boolean(value)});if(!value)throw new Error(name);};
  const click=selector=>{const element=document.querySelector(selector);if(!element)throw new Error(selector);element.click();};
  const change=(selector,value)=>{const element=document.querySelector(selector);element.value=value;element.dispatchEvent(new Event('change',{bubbles:true}));};
  const query=value=>{const element=document.getElementById('catalogue-query');element.value=value;element.dispatchEvent(new Event('input',{bubbles:true}));};
  const text=()=>document.getElementById('screen').textContent;
  const results=()=>[...document.querySelectorAll('#catalogue-results [data-entry]')];
  const reset=()=>change('#scenario','password');
  const modal=document.getElementById('explanation');
  if(modal.open)click('[data-action="dismiss"]');
  reset();
  check('列表有可用搜索框',Boolean(document.getElementById('catalogue-query')));
  check('默认当前分类',document.getElementById('catalogue-scope').value==='category'&&results().length===3);
  query('mail');check('账户可搜索',results().length===1&&results()[0].textContent.includes('私人邮箱'));
  query('护照');check('本类不会混入证件',results().length===0&&text().includes('没有找到匹配条目'));
  change('#catalogue-scope','all');check('显式跨类别搜索',results().length===1&&results()[0].textContent.includes('护照'));
  query('开发账户');check('全库按条目去重',results().length===1);
  query('DEMO-only-not-a-secret');check('搜索不匹配密码内容',results().length===0);
  query('');click('[data-action="favorite-filter"]');check('收藏筛选',results().length===2);
  change('#catalogue-group','出行');check('组合分组筛选',results().length===1&&results()[0].dataset.entry==='passport');
  click('[data-entry="passport"]');
  let secrets=[...document.querySelectorAll('.field-value.mono')];
  check('两个秘密字段默认遮罩',secrets.length===2&&secrets.every(x=>x.textContent.includes('••••')));
  click('[data-field="持有人"]');
  secrets=[...document.querySelectorAll('.field-value.mono')];
  check('只显示选中字段',secrets[0].textContent==='演示用户'&&secrets[1].textContent.includes('••••'));
  click('[data-field="证件号码"]');check('第二字段独立显示',document.querySelector('[data-field="证件号码"]').getAttribute('aria-pressed')==='true');
  click('[data-field="持有人"]');check('隐藏第一项不影响第二项',document.querySelector('[data-field="持有人"]').getAttribute('aria-pressed')==='false'&&document.querySelector('[data-field="证件号码"]').getAttribute('aria-pressed')==='true');
  click('#back');check('返回保留搜索范围与分组',document.getElementById('catalogue-scope').value==='all'&&document.getElementById('catalogue-group').value==='出行');
  reset();query('私人');click('[data-tab="verify"]');click('[data-tab="password"]');check('切tab保留原搜索',document.getElementById('catalogue-query').value==='私人');
  click('.lock-button');click('[data-action="unlock"]');check('锁定清理搜索提示',document.getElementById('catalogue-query').value==='');
  reset();click('[data-action="add"]');check('新增先选类型',text().includes('新建条目')&&text().includes('API 凭据'));
  click('[data-route="editor"][data-kind="login"]');check('编辑布局不接受秘密输入',[...document.querySelectorAll('#screen input')].length>=4&&[...document.querySelectorAll('#screen input')].every(x=>x.disabled));
  click('[data-route="generator-preview"]');check('生成器在字段上下文',text().includes('不自动修改网站密码'));
  click('#back');check('生成器可返回编辑',text().includes('编辑条目'));
  click('[data-action="save-layout"]');check('保存按钮不假装写入',modal.textContent.includes('没有保存任何内容'));click('[data-action="dismiss"]');
  click('[data-route="custom-fields"]');check('自定义字段映射提示',text().includes('布尔型')&&text().includes('不承诺移动系统'));
  reset();click('[data-entry="developer"]');click('[data-route="item-actions"]');
  click('[data-action="clone-item"]');check('克隆不复制Passkey及其他秘密类型',modal.textContent.includes('排除Passkey')&&modal.textContent.includes('SSH私钥'));click('[data-action="dismiss"]');
  click('[data-action="trash-item"]');check('删除只是流程预览',modal.textContent.includes('没有删除任何条目'));click('[data-action="dismiss"]');
  const oldFavorite=document.querySelector('[data-action="favorite-item"]').getAttribute('aria-pressed');
  click('[data-action="favorite-item"]');check('详情收藏可切换',document.querySelector('[data-action="favorite-item"]').getAttribute('aria-pressed')!==oldFavorite);click('[data-action="favorite-item"]');
  click('[data-route="uri-rules"]');check('匹配不静默降级',text().includes('不静默放宽'));
  check('再次验证不是加密',text().includes('不是额外加密')&&text().includes('不能强制其他KDBX客户端'));
  reset();click('[data-tab="verify"]');while(!document.getElementById('back').disabled)click('#back');click('[data-action="add"]');click('[data-route="passkey-create-info"]');check('Passkey创建需网站请求',modal.textContent.includes('合法网站/应用'));click('[data-action="dismiss"]');
  reset();check('页面无横向溢出',document.documentElement.scrollWidth<=innerWidth);
  check('主导航仍为五项',document.querySelectorAll('#tabs [data-tab]').length===5);
  check('无外部网络资源',performance.getEntriesByType('resource').every(x=>new URL(x.name).origin===location.origin));
  const report={viewport:[innerWidth,innerHeight],passed:checks.filter(x=>x.passed).length,failed:checks.filter(x=>!x.passed).length,checks,scope:'合成HTML原型，非Flutter/原生功能'};
  window.__keexMobilePatternReport=report;return report;
};
